CREATE TABLE IF NOT EXISTS user_businesses (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES app_users(id) ON DELETE CASCADE,
    business_id BIGINT NOT NULL REFERENCES businesses(id) ON DELETE CASCADE,
    role VARCHAR(32) NOT NULL DEFAULT 'staff',
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (user_id, business_id)
);

CREATE TABLE IF NOT EXISTS business_settings (
    business_id BIGINT NOT NULL,
    key VARCHAR(128) NOT NULL,
    value TEXT NOT NULL,
    updated_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (business_id, key)
);

CREATE TABLE IF NOT EXISTS offers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_id BIGINT NOT NULL,
    name VARCHAR(255) NOT NULL,
    offer_type VARCHAR(64) NOT NULL,
    discount_type VARCHAR(32) NOT NULL,
    discount_value NUMERIC(14, 3) NOT NULL DEFAULT 0,
    min_qty NUMERIC(14, 3) NOT NULL DEFAULT 0,
    min_amount NUMERIC(14, 3) NOT NULL DEFAULT 0,
    apply_to VARCHAR(32) NOT NULL DEFAULT 'all',
    target_id BIGINT,
    buy_qty NUMERIC(14, 3) NOT NULL DEFAULT 0,
    get_qty NUMERIC(14, 3) NOT NULL DEFAULT 0,
    start_date TIMESTAMP WITHOUT TIME ZONE,
    end_date TIMESTAMP WITHOUT TIME ZONE,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    poster_url TEXT,
    poster_public_id VARCHAR(255),
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_offer_dates CHECK (start_date IS NULL OR end_date IS NULL OR end_date >= start_date),
    CONSTRAINT ck_offer_value CHECK (discount_value >= 0)
);

CREATE TABLE IF NOT EXISTS loyalty_transactions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_id BIGINT NOT NULL,
    customer_id BIGINT NOT NULL,
    adjustment NUMERIC(14, 3) NOT NULL,
    reason TEXT,
    created_by VARCHAR(128),
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_offers_business_active ON offers (business_id, is_active, start_date, end_date);
CREATE INDEX IF NOT EXISTS idx_loyalty_business_customer ON loyalty_transactions (business_id, customer_id, created_at DESC);

CREATE TABLE IF NOT EXISTS auth_sessions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES app_users(id) ON DELETE CASCADE,
    business_id BIGINT,
    token_hash VARCHAR(64) NOT NULL UNIQUE,
    expires_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS customer_discounts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_id BIGINT NOT NULL,
    customer_id BIGINT NOT NULL,
    discount_percentage NUMERIC(6, 3) NOT NULL DEFAULT 0,
    discount_amount NUMERIC(14, 3) NOT NULL DEFAULT 0,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    UNIQUE (business_id, customer_id)
);

CREATE TABLE IF NOT EXISTS product_discounts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_id BIGINT NOT NULL,
    product_id BIGINT NOT NULL,
    discount_percentage NUMERIC(6, 3) NOT NULL DEFAULT 0,
    discount_amount NUMERIC(14, 3) NOT NULL DEFAULT 0,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    UNIQUE (business_id, product_id)
);
