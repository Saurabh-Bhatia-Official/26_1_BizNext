CREATE TABLE product_categories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_id BIGINT NOT NULL,
    name VARCHAR(255) NOT NULL,
    code VARCHAR(64),
    description TEXT,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_product_category_business_name UNIQUE (business_id, name),
    CONSTRAINT uq_product_category_id_business UNIQUE (id, business_id)
);

CREATE TABLE products (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_id BIGINT NOT NULL,
    product_name VARCHAR(255) NOT NULL,
    sku VARCHAR(128),
    category_id BIGINT,
    brand VARCHAR(255),
    description TEXT,
    purchase_price NUMERIC(14, 2) NOT NULL DEFAULT 0,
    mrp NUMERIC(14, 2) NOT NULL DEFAULT 0,
    selling_price NUMERIC(14, 2) NOT NULL DEFAULT 0,
    min_selling_price NUMERIC(14, 2) NOT NULL DEFAULT 0,
    wholesale_price NUMERIC(14, 2) NOT NULL DEFAULT 0,
    dealer_price NUMERIC(14, 2) NOT NULL DEFAULT 0,
    tax_percentage NUMERIC(6, 3) NOT NULL DEFAULT 0,
    stock_quantity NUMERIC(14, 3) NOT NULL DEFAULT 0,
    minimum_stock_level NUMERIC(14, 3) NOT NULL DEFAULT 5,
    unit VARCHAR(32) NOT NULL DEFAULT 'pcs',
    barcode VARCHAR(128),
    hsn_sac VARCHAR(64),
    product_image TEXT,
    product_image_public_id VARCHAR(255),
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_products_category_business
        FOREIGN KEY (category_id, business_id)
        REFERENCES product_categories (id, business_id) ON DELETE SET NULL (category_id),
    CONSTRAINT ck_products_prices_nonnegative CHECK (
        purchase_price >= 0 AND mrp >= 0 AND selling_price >= 0
        AND min_selling_price >= 0 AND wholesale_price >= 0 AND dealer_price >= 0
    ),
    CONSTRAINT ck_products_stock_nonnegative CHECK (
        stock_quantity >= 0 AND minimum_stock_level >= 0
    ),
    CONSTRAINT ck_products_tax_percentage CHECK (tax_percentage >= 0 AND tax_percentage <= 100)
);

CREATE UNIQUE INDEX uq_products_business_sku
    ON products (business_id, LOWER(sku))
    WHERE sku IS NOT NULL AND BTRIM(sku) <> '';
CREATE INDEX idx_products_business_name ON products (business_id, LOWER(product_name));
CREATE INDEX idx_products_business_category ON products (business_id, category_id);
CREATE INDEX idx_products_business_brand ON products (business_id, LOWER(brand));
CREATE INDEX idx_products_business_status ON products (business_id, is_active);
CREATE INDEX idx_products_business_stock ON products (business_id, stock_quantity, minimum_stock_level);
CREATE INDEX idx_products_created_at ON products (business_id, created_at DESC);
