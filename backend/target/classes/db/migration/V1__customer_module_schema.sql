CREATE TABLE customer_types (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_id BIGINT NOT NULL DEFAULT 1,
    name VARCHAR(255) NOT NULL,
    code VARCHAR(64),
    description TEXT,
    is_active INTEGER NOT NULL DEFAULT 1,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_customer_type_business_name UNIQUE (business_id, name)
);

CREATE TABLE customers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_id BIGINT NOT NULL,
    name VARCHAR(255) NOT NULL,
    phone VARCHAR(32),
    phone_normalized VARCHAR(15) GENERATED ALWAYS AS (
        regexp_replace(COALESCE(phone, ''), '[^0-9]', '', 'g')
    ) STORED,
    email VARCHAR(255),
    address TEXT,
    gst_number VARCHAR(255),
    customer_type_id BIGINT,
    balance DOUBLE PRECISION NOT NULL DEFAULT 0,
    loyalty_points DOUBLE PRECISION NOT NULL DEFAULT 0,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_customers_customer_type
        FOREIGN KEY (customer_type_id) REFERENCES customer_types(id) ON DELETE SET NULL
);

CREATE INDEX idx_customers_business_name ON customers (business_id, name);
CREATE UNIQUE INDEX uq_customers_business_normalized_phone
    ON customers (business_id, phone_normalized)
    WHERE phone_normalized <> '';

CREATE TABLE sales (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_id BIGINT NOT NULL,
    invoice_no VARCHAR(255) NOT NULL,
    customer_id BIGINT,
    subtotal DOUBLE PRECISION NOT NULL DEFAULT 0,
    discount DOUBLE PRECISION NOT NULL DEFAULT 0,
    gst_amount DOUBLE PRECISION NOT NULL DEFAULT 0,
    grand_total DOUBLE PRECISION NOT NULL DEFAULT 0,
    paid_amount DOUBLE PRECISION NOT NULL DEFAULT 0,
    balance_due DOUBLE PRECISION NOT NULL DEFAULT 0,
    payment_mode VARCHAR(64) NOT NULL DEFAULT 'Cash',
    account_id BIGINT,
    notes TEXT,
    status VARCHAR(64) NOT NULL DEFAULT 'completed',
    points_earned DOUBLE PRECISION NOT NULL DEFAULT 0,
    points_redeemed DOUBLE PRECISION NOT NULL DEFAULT 0,
    loyalty_discount DOUBLE PRECISION NOT NULL DEFAULT 0,
    date TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_sales_business_invoice UNIQUE (business_id, invoice_no),
    CONSTRAINT fk_sales_customer FOREIGN KEY (customer_id) REFERENCES customers(id) ON DELETE SET NULL
);

CREATE INDEX idx_sales_business_customer ON sales (business_id, customer_id);

CREATE TABLE ledger (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_id BIGINT NOT NULL DEFAULT 1,
    entity_type VARCHAR(64) NOT NULL,
    entity_id BIGINT NOT NULL,
    type VARCHAR(32) NOT NULL DEFAULT 'debit',
    amount DOUBLE PRECISION NOT NULL DEFAULT 0,
    balance DOUBLE PRECISION NOT NULL DEFAULT 0,
    reference_id BIGINT,
    account_id BIGINT,
    description TEXT,
    date TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_ledger_business_entity ON ledger (business_id, entity_type, entity_id);
