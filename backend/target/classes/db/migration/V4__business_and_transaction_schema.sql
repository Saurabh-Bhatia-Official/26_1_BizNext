CREATE TABLE IF NOT EXISTS businesses (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    type VARCHAR(128) NOT NULL DEFAULT 'Retail Shop',
    address TEXT,
    phone VARCHAR(32),
    email VARCHAR(255),
    gst_number VARCHAR(255),
    currency VARCHAR(16) NOT NULL DEFAULT 'INR',
    currency_symbol VARCHAR(8) NOT NULL DEFAULT '₹',
    logo_url TEXT,
    logo_public_id VARCHAR(255),
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
ALTER TABLE businesses ADD COLUMN IF NOT EXISTS owner_id BIGINT;

CREATE TABLE IF NOT EXISTS app_users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_id BIGINT,
    username VARCHAR(128) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    full_name VARCHAR(255) NOT NULL,
    email VARCHAR(255),
    phone VARCHAR(32),
    role VARCHAR(32) NOT NULL DEFAULT 'staff',
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    profile_image_url TEXT,
    profile_image_public_id VARCHAR(255),
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (business_id, username)
);

CREATE TABLE IF NOT EXISTS suppliers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_id BIGINT NOT NULL,
    name VARCHAR(255) NOT NULL,
    phone VARCHAR(32),
    email VARCHAR(255),
    address TEXT,
    gst_number VARCHAR(255),
    balance NUMERIC(14, 3) NOT NULL DEFAULT 0,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_suppliers_business_name UNIQUE (business_id, name)
);

CREATE TABLE IF NOT EXISTS purchases (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_id BIGINT NOT NULL,
    supplier_id BIGINT,
    invoice_no VARCHAR(255) NOT NULL,
    subtotal NUMERIC(14, 3) NOT NULL DEFAULT 0,
    discount NUMERIC(14, 3) NOT NULL DEFAULT 0,
    tax_amount NUMERIC(14, 3) NOT NULL DEFAULT 0,
    grand_total NUMERIC(14, 3) NOT NULL DEFAULT 0,
    paid_amount NUMERIC(14, 3) NOT NULL DEFAULT 0,
    balance_due NUMERIC(14, 3) NOT NULL DEFAULT 0,
    payment_status VARCHAR(32) NOT NULL DEFAULT 'unpaid',
    status VARCHAR(32) NOT NULL DEFAULT 'completed',
    document_url TEXT,
    document_public_id VARCHAR(255),
    date TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_purchases_business_invoice UNIQUE (business_id, invoice_no),
    CONSTRAINT fk_purchases_supplier FOREIGN KEY (supplier_id) REFERENCES suppliers(id) ON DELETE SET NULL
);

CREATE TABLE IF NOT EXISTS purchase_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    purchase_id BIGINT NOT NULL REFERENCES purchases(id) ON DELETE CASCADE,
    product_id BIGINT,
    quantity NUMERIC(14, 3) NOT NULL,
    purchase_price NUMERIC(14, 3) NOT NULL,
    discount NUMERIC(14, 3) NOT NULL DEFAULT 0,
    tax_amount NUMERIC(14, 3) NOT NULL DEFAULT 0,
    total_amount NUMERIC(14, 3) NOT NULL
);

CREATE TABLE IF NOT EXISTS sale_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sale_id BIGINT NOT NULL REFERENCES sales(id) ON DELETE CASCADE,
    product_id BIGINT,
    quantity NUMERIC(14, 3) NOT NULL,
    unit_price NUMERIC(14, 3) NOT NULL,
    purchase_price NUMERIC(14, 3) NOT NULL DEFAULT 0,
    discount NUMERIC(14, 3) NOT NULL DEFAULT 0,
    tax_amount NUMERIC(14, 3) NOT NULL DEFAULT 0,
    total_amount NUMERIC(14, 3) NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_suppliers_business_name ON suppliers (business_id, name);
CREATE INDEX IF NOT EXISTS idx_purchases_business_date ON purchases (business_id, date DESC);
